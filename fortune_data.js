// 根据日期与法殿智能获取当天确定签文 (Daily Seeded Hash)
function getDailyFortuneSlip(dateStr, templeId) {
    const d = new Date();
    const dateKey = dateStr || `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
    let hash = 0;
    for (let i = 0; i < dateKey.length; i++) {
        hash = ((hash << 5) - hash) + dateKey.charCodeAt(i);
        hash |= 0;
    }
    hash = Math.abs(hash);
    
    // 如果法殿有专属签，优先根据法殿偏移
    let filtered = FORTUNE_SLIPS;
    if (templeId === 'wenchang') {
        filtered = FORTUNE_SLIPS.filter(s => s.name.includes('文昌') || s.name.includes('第一') || s.name.includes('仙鹤') || s.name.includes('鹏程') || s.name.includes('姜公'));
    } else if (templeId === 'wealth') {
        filtered = FORTUNE_SLIPS.filter(s => s.name.includes('财神') || s.name.includes('金玉') || s.name.includes('锦上') || s.name.includes('乾坤'));
    } else if (templeId === 'jieyou') {
        filtered = FORTUNE_SLIPS.filter(s => s.name.includes('解忧') || s.name.includes('清风') || s.name.includes('明月') || s.name.includes('灵泉') || s.name.includes('渔樵'));
    }
    
    if (!filtered.length) filtered = FORTUNE_SLIPS;
    const slipIdx = hash % filtered.length;
    return filtered[slipIdx];
}

